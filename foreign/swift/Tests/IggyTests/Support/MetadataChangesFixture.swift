import Foundation

/// The cross-SDK metadata changes fixture, generated by
/// `core/common/examples/metadata_changes_fixtures.rs` from the real Rust
/// codecs and copied byte for byte into every SDK. Never edit the copy. Its
/// `expected` objects are the JSON the HTTP route renders, so they load as
/// ``JSONValue`` trees the tests compare whole.
enum MetadataChangesFixture {
    static let shared: JSONValue = {
        let url = Bundle.module.url(forResource: "metadata_changes", withExtension: "json", subdirectory: "Fixtures")!
        let data = try! Data(contentsOf: url)
        return try! JSONDecoder().decode(JSONValue.self, from: data)
    }()
}

/// A JSON document. Every number in the fixture is an unsigned integer.
enum JSONValue: Decodable, Equatable, Sendable, CustomStringConvertible {
    case null
    case bool(Bool)
    case number(UInt64)
    case string(String)
    case array([JSONValue])
    case object([String: JSONValue])

    init(from decoder: any Decoder) throws {
        let container = try decoder.singleValueContainer()
        if container.decodeNil() {
            self = .null
        } else if let value = try? container.decode(Bool.self) {
            self = .bool(value)
        } else if let value = try? container.decode(UInt64.self) {
            self = .number(value)
        } else if let value = try? container.decode(String.self) {
            self = .string(value)
        } else if let value = try? container.decode([JSONValue].self) {
            self = .array(value)
        } else {
            self = .object(try container.decode([String: JSONValue].self))
        }
    }

    /// The member named `key`, or null when this is not an object or has no such member.
    subscript(key: String) -> JSONValue {
        if case .object(let members) = self {
            return members[key] ?? .null
        }
        return .null
    }

    var isNull: Bool { self == .null }

    var string: String {
        if case .string(let value) = self {
            return value
        }
        return ""
    }

    var number: UInt64 {
        if case .number(let value) = self {
            return value
        }
        return 0
    }

    var array: [JSONValue] {
        if case .array(let values) = self {
            return values
        }
        return []
    }

    var members: [String: JSONValue] {
        if case .object(let members) = self {
            return members
        }
        return [:]
    }

    var description: String {
        switch self {
        case .null: "null"
        case .bool(let value): String(value)
        case .number(let value): String(value)
        case .string(let value): "\"\(value)\""
        case .array(let values): "[\(values.map(\.description).joined(separator: ","))]"
        case .object(let members): "{\(members.sorted { $0.key < $1.key }.map { "\"\($0.key)\":\($0.value)" }.joined(separator: ","))}"
        }
    }
}

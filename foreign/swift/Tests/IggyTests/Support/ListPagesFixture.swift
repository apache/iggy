/// The cross-SDK list page fixture, generated by
/// `core/common/examples/list_pages_fixtures.rs` from the real Rust codecs and
/// copied byte for byte into every SDK. Never edit the copy. Each vector group
/// is a required key, so a renamed group fails the load instead of reading as
/// empty.
struct ListPagesFixture: Decodable, Sendable {
    static let shared: ListPagesFixture = {
        let url = Bundle.module.url(forResource: "list_pages", withExtension: "json", subdirectory: "Fixtures")!
        return try! JSONDecoder().decode(ListPagesFixture.self, from: Data(contentsOf: url))
    }()

    struct Constants: Decodable, Sendable {
        let codes: [String: UInt32]
        let orders: [String: UInt8]
        let cursorPrefix: String
        let maxCursorBytes: Int
        let defaultLimit: UInt32
        let maxLimit: UInt32
        let maxNameBytes: Int
        let errors: [String: UInt32]

        enum CodingKeys: String, CodingKey {
            case codes, orders, errors
            case cursorPrefix = "cursor_prefix"
            case maxCursorBytes = "max_cursor_bytes"
            case defaultLimit = "default_limit"
            case maxLimit = "max_limit"
            case maxNameBytes = "max_name_bytes"
        }
    }

    struct Cursor: Decodable, Sendable {
        let name: String
        let text: String
        let hex: String

        enum CodingKeys: String, CodingKey {
            case name = "case"
            case text, hex
        }
    }

    /// A stream or topic id: `kind` numeric with a `UInt32` value, or named
    /// with a string value.
    struct ParentID: Decodable, Sendable {
        let identifier: Identifier

        enum CodingKeys: String, CodingKey {
            case kind, value
        }

        init(from decoder: any Decoder) throws {
            let container = try decoder.container(keyedBy: CodingKeys.self)
            switch try container.decode(String.self, forKey: .kind) {
            case "numeric":
                identifier = Identifier(numeric: try container.decode(UInt32.self, forKey: .value))
            case "named":
                identifier = try Identifier(named: try container.decode(String.self, forKey: .value))
            case let kind:
                throw DecodingError.dataCorruptedError(forKey: .kind, in: container, debugDescription: "unknown identifier kind \(kind)")
            }
        }
    }

    struct Input: Decodable, Sendable {
        let streamID: ParentID?
        let topicID: ParentID?
        let order: String
        let descending: Bool
        let limit: UInt32
        let cursor: String?
        let name: String?

        enum CodingKeys: String, CodingKey {
            case order, descending, limit, cursor, name
            case streamID = "stream_id"
            case topicID = "topic_id"
        }
    }

    struct Request: Decodable, Sendable {
        let name: String
        let command: String
        let input: Input
        let requestHex: String

        enum CodingKeys: String, CodingKey {
            case name = "case"
            case command, input
            case requestHex = "request_hex"
        }
    }

    struct Item: Decodable, Sendable, Equatable {
        let id: UInt32
        /// Nil for a partition, which has no name.
        let name: String?
    }

    struct Response: Decodable, Sendable {
        let name: String
        let command: String
        let responseHex: String
        let next: String?
        let items: [Item]

        enum CodingKeys: String, CodingKey {
            case name = "case"
            case command, next, items
            case responseHex = "response_hex"
        }
    }

    struct RefusedCursor: Decodable, Sendable {
        let name: String
        let text: String

        enum CodingKeys: String, CodingKey {
            case name = "case"
            case text
        }
    }

    struct RefusedQuery: Decodable, Sendable {
        let name: String
        let input: Input

        enum CodingKeys: String, CodingKey {
            case name = "case"
            case input
        }
    }

    struct RefusedResponse: Decodable, Sendable {
        let name: String
        let command: String
        let responseHex: String

        enum CodingKeys: String, CodingKey {
            case name = "case"
            case command
            case responseHex = "response_hex"
        }
    }

    struct Refused: Decodable, Sendable {
        let cursors: [RefusedCursor]
        let queries: [RefusedQuery]
        let responses: [RefusedResponse]
    }

    let schemaVersion: Int
    let constants: Constants
    let cursors: [Cursor]
    let opaqueCursors: [Cursor]
    let requests: [Request]
    let responses: [Response]
    let opaqueResponses: [Response]
    let refused: Refused

    enum CodingKeys: String, CodingKey {
        case constants, cursors, requests, responses, refused
        case schemaVersion = "schema_version"
        case opaqueCursors = "opaque_cursors"
        case opaqueResponses = "opaque_responses"
    }
}

/// Cursors as the server writes them, for tests that script replies. The
/// client itself never reads the bytes of a cursor.
extension PageCursor {
    static let idKind: UInt8 = 1
    static let createdKind: UInt8 = 2

    /// `[kind:u8][id:u64]`, a position in id order.
    static func id(_ id: UInt64) -> PageCursor? {
        PageCursor(bytes: [idKind] + id.littleEndianBytes)
    }

    /// `[kind:u8][created_at:u64][id:u64]`, a position in creation order.
    static func created(at createdAt: UInt64, id: UInt64) -> PageCursor? {
        PageCursor(bytes: [createdKind] + createdAt.littleEndianBytes + id.littleEndianBytes)
    }
}

import Foundation

/// The cross-SDK resource options fixture, generated by
/// `core/common/examples/resource_options_fixtures.rs` from the real Rust
/// encoders and copied byte for byte into every SDK. Never edit the copy.
struct ResourceOptionsFixture: Decodable, Sendable {
    struct Version: Decodable {
        let packed: UInt32
        let text: String
    }

    struct CommandEntry: Decodable {
        let code: UInt32
        let operation: UInt8?
    }

    struct OperationEntry: Decodable {
        let value: UInt8
        let `internal`: Bool
        let requestOperation: UInt8

        enum CodingKeys: String, CodingKey {
            case value
            case `internal`
            case requestOperation = "request_operation"
        }
    }

    struct Constants: Decodable {
        let protocolVersion: Version
        let protocolVersionMin: Version
        let commandCodes: [String: CommandEntry]
        let retiredCommandCodes: [String: UInt32]
        let operations: [String: OperationEntry]
        let retiredOperations: [String: UInt8]
        let scopeCodes: [String: UInt8]
        let headerKindCodes: [String: UInt8]
        let optionFlags: [String: UInt8]
        let userStatusCodes: [String: UInt8]
        let streamKeyLength: Int
        let neverReturnedKeys: [String]

        enum CodingKeys: String, CodingKey {
            case protocolVersion = "protocol_version"
            case protocolVersionMin = "protocol_version_min"
            case commandCodes = "command_codes"
            case retiredCommandCodes = "retired_command_codes"
            case operations
            case retiredOperations = "retired_operations"
            case scopeCodes = "scope_codes"
            case headerKindCodes = "header_kind_codes"
            case optionFlags = "option_flags"
            case userStatusCodes = "user_status_codes"
            case streamKeyLength = "stream_key_length"
            case neverReturnedKeys = "never_returned_keys"
        }
    }

    struct CatalogRow: Decodable {
        let key: String
        let scopes: [String]
        let kind: String
        let kindCode: UInt8
        let storage: String
        let mutability: String
        let visibility: String
        let critical: Bool
        let flags: UInt8
        let described: Bool

        enum CodingKeys: String, CodingKey {
            case key, scopes, kind, storage, mutability, visibility, critical, flags, described
            case kindCode = "kind_code"
        }
    }

    struct DescribeEntry: Decodable {
        let key: String
        let kind: String
        let flags: UInt8
        let defaultValue: String?

        enum CodingKeys: String, CodingKey {
            case key, kind, flags
            case defaultValue = "default"
        }
    }

    struct DescribeVector: Decodable {
        let scope: String
        let requestHex: String
        let responseHex: String
        let entries: [DescribeEntry]

        enum CodingKeys: String, CodingKey {
            case scope, entries
            case requestHex = "request_hex"
            case responseHex = "response_hex"
        }
    }

    struct ErrorRef: Decodable {
        let name: String
        let code: UInt32
    }

    /// A stream key as 32 raw bytes or as base64 text.
    struct KeyInput: Decodable {
        let rawHex: String?
        let base64: String?

        enum CodingKeys: String, CodingKey {
            case rawHex = "raw_hex"
            case base64
        }
    }

    struct InvalidKey: Decodable {
        let name: String
        let input: KeyInput
        let error: ErrorRef

        enum CodingKeys: String, CodingKey {
            case name = "case"
            case input, error
        }
    }

    struct StreamKey: Decodable {
        let keyHex: String
        let keyBase64: String
        let fingerprint: String
        let invalidKeys: [InvalidKey]

        enum CodingKeys: String, CodingKey {
            case fingerprint
            case keyHex = "key_hex"
            case keyBase64 = "key_base64"
            case invalidKeys = "invalid_keys"
        }
    }

    /// A target id: a number is a numeric id, a string a named one.
    enum TargetID: Decodable {
        case numeric(UInt32)
        case named(String)

        init(from decoder: Decoder) throws {
            let container = try decoder.singleValueContainer()
            if let numeric = try? container.decode(UInt32.self) {
                self = .numeric(numeric)
            } else {
                self = .named(try container.decode(String.self))
            }
        }
    }

    /// Typed update input. u64 values are decimal strings.
    struct UpdateInput: Decodable {
        let name: String?
        let username: String?
        let status: String?
        let messageExpiry: String?
        let maxTopicSize: String?
        let reset: [String]?

        enum CodingKeys: String, CodingKey {
            case name, username, status, reset
            case messageExpiry = "message_expiry"
            case maxTopicSize = "max_topic_size"
        }
    }

    struct UpdateVector: Decodable {
        let name: String
        let scope: String
        let target: [String: TargetID]
        let input: UpdateInput
        let wireReset: [String]
        let bodyHex: String

        enum CodingKeys: String, CodingKey {
            case name = "case"
            case scope, target, input
            case wireReset = "wire_reset"
            case bodyHex = "body_hex"
        }
    }

    struct UpdateErrorVector: Decodable {
        let name: String
        let scope: String
        let target: [String: TargetID]
        let input: UpdateInput
        let error: ErrorRef

        enum CodingKeys: String, CodingKey {
            case name = "case"
            case scope, target, input, error
        }
    }

    struct CreateStreamInput: Decodable {
        let name: String
        let encryptionKey: KeyInput?
        let raw: [String: String]?

        enum CodingKeys: String, CodingKey {
            case name, raw
            case encryptionKey = "encryption_key"
        }
    }

    struct CreateStreamVector: Decodable {
        let name: String
        let input: CreateStreamInput
        let bodyHex: String
        let admissionError: ErrorRef?

        enum CodingKeys: String, CodingKey {
            case name = "case"
            case input
            case bodyHex = "body_hex"
            case admissionError = "admission_error"
        }
    }

    struct CreateTopicInput: Decodable {
        let streamID: TargetID
        let name: String
        let partitionsCount: UInt32
        let compressionAlgorithm: String
        let messageExpiry: String
        let maxTopicSize: String
        let segmentSize: String
        let durability: String
        let consumerOffsetDurability: String

        enum CodingKeys: String, CodingKey {
            case name, durability
            case streamID = "stream_id"
            case partitionsCount = "partitions_count"
            case compressionAlgorithm = "compression_algorithm"
            case messageExpiry = "message_expiry"
            case maxTopicSize = "max_topic_size"
            case segmentSize = "segment_size"
            case consumerOffsetDurability = "consumer_offset_durability"
        }
    }

    struct CreateTopicVector: Decodable {
        let name: String
        let input: CreateTopicInput
        let bodyHex: String

        enum CodingKeys: String, CodingKey {
            case name = "case"
            case input
            case bodyHex = "body_hex"
        }
    }

    struct CreateUserInput: Decodable {
        let username: String
        let password: String
        let status: String
    }

    struct CreateUserVector: Decodable {
        let name: String
        let input: CreateUserInput
        let bodyHex: String

        enum CodingKeys: String, CodingKey {
            case name = "case"
            case input
            case bodyHex = "body_hex"
        }
    }

    /// One option in the HTTP JSON form: reversible text, kind, provenance.
    struct OptionEntry: Decodable, Equatable {
        let value: String
        let kind: String
        let explicit: Bool
    }

    struct StreamProjection: Decodable {
        let id: UInt32
        let createdAt: UInt64
        let name: String
        let topicsCount: UInt32
        let sizeBytes: UInt64
        let messagesCount: UInt64
        let options: [String: OptionEntry]
        let encryptionKeySource: String
        let encryptionKeyFingerprint: String?
        let encryptionKekFingerprints: [String]

        enum CodingKeys: String, CodingKey {
            case id, name, options
            case createdAt = "created_at"
            case topicsCount = "topics_count"
            case sizeBytes = "size_bytes"
            case messagesCount = "messages_count"
            case encryptionKeySource = "encryption_key_source"
            case encryptionKeyFingerprint = "encryption_key_fingerprint"
            case encryptionKekFingerprints = "encryption_kek_fingerprints"
        }
    }

    struct TopicProjection: Decodable {
        let id: UInt32
        let createdAt: UInt64
        let name: String
        let partitionsCount: UInt32
        let sizeBytes: UInt64
        let messagesCount: UInt64
        let options: [String: OptionEntry]
        let compressionAlgorithm: String
        let messageExpiry: String
        let maxTopicSize: String

        enum CodingKeys: String, CodingKey {
            case id, name, options
            case createdAt = "created_at"
            case partitionsCount = "partitions_count"
            case sizeBytes = "size_bytes"
            case messagesCount = "messages_count"
            case compressionAlgorithm = "compression_algorithm"
            case messageExpiry = "message_expiry"
            case maxTopicSize = "max_topic_size"
        }
    }

    struct UserProjection: Decodable {
        let id: UInt32
        let createdAt: UInt64
        let status: String
        let username: String
        let options: [String: OptionEntry]

        enum CodingKeys: String, CodingKey {
            case id, status, username, options
            case createdAt = "created_at"
        }
    }

    struct ResponseVector<Projection: Decodable & Sendable>: Decodable, Sendable {
        let name: String
        let responseHex: String
        let expected: Projection

        enum CodingKeys: String, CodingKey {
            case name = "case"
            case expected
            case responseHex = "response_hex"
        }
    }

    let schemaVersion: Int
    let constants: Constants
    let catalog: [CatalogRow]
    let describeOptions: [DescribeVector]
    let streamKey: StreamKey
    let updateResource: [UpdateVector]
    let updateResourceErrors: [UpdateErrorVector]
    let createStream: [CreateStreamVector]
    let createTopic: [CreateTopicVector]
    let createUser: [CreateUserVector]
    let streamResponses: [ResponseVector<StreamProjection>]
    let topicResponses: [ResponseVector<TopicProjection>]
    let userResponses: [ResponseVector<UserProjection>]

    enum CodingKeys: String, CodingKey {
        case constants, catalog
        case schemaVersion = "schema_version"
        case describeOptions = "describe_options"
        case streamKey = "stream_key"
        case updateResource = "update_resource"
        case updateResourceErrors = "update_resource_errors"
        case createStream = "create_stream"
        case createTopic = "create_topic"
        case createUser = "create_user"
        case streamResponses = "stream_responses"
        case topicResponses = "topic_responses"
        case userResponses = "user_responses"
    }

    static let shared: ResourceOptionsFixture = {
        let url = Bundle.module.url(forResource: "resource_options", withExtension: "json", subdirectory: "Fixtures")!
        let data = try! Data(contentsOf: url)
        return try! JSONDecoder().decode(ResourceOptionsFixture.self, from: data)
    }()
}

/// The wire vectors of deferred polling that every SDK shares, generated by
/// `core/common/examples/deferred_polling_fixtures.rs`. Never edit the copy.
private struct DeferredPollingFixture: Decodable {
    struct WireIdentifier: Decodable {
        let kind: String
        let value: StringOrNumber
    }

    /// A numeric identifier is a JSON number, a named one a string.
    enum StringOrNumber: Decodable {
        case number(UInt32)
        case string(String)

        init(from decoder: any Decoder) throws {
            let container = try decoder.singleValueContainer()
            if let number = try? container.decode(UInt32.self) {
                self = .number(number)
            } else {
                self = .string(try container.decode(String.self))
            }
        }
    }

    struct WireConsumer: Decodable {
        let kind: UInt8
        let id: WireIdentifier
    }

    struct Strategy: Decodable {
        let kind: UInt8
        let value: UInt64
    }

    struct DeferredPoll: Decodable {
        let consumer: WireConsumer
        let streamId: WireIdentifier
        let topicId: WireIdentifier
        let partitionId: UInt32
        let strategy: Strategy
        let count: UInt32
        let autoCommit: Bool
        let waitUs: UInt64
        let minCount: UInt32
        let maxBytes: UInt32
        let requestTimeoutUs: UInt64
    }

    struct Target: Decodable {
        let partitionId: UInt32
        let strategy: Strategy
        let maxBytes: UInt32
        let incarnation: UInt64
        let ownerGeneration: UInt64
    }

    struct Fetch: Decodable {
        let consumer: WireConsumer
        let streamId: WireIdentifier
        let topicId: WireIdentifier
        let waitUs: UInt64
        let requestTimeoutUs: UInt64
        let minCount: UInt32
        let count: UInt32
        let maxBytes: UInt32
        let autoCommit: Bool
        let targets: [Target]
    }

    struct Case<Request: Decodable>: Decodable {
        let `case`: String
        let request: Request
        let bodyHex: String
    }

    struct Cancellation: Decodable {
        let `case`: String
        let cancelsCode: UInt32
        let client: UInt64
        let request: UInt64
        let session: UInt64
        let headerHex: String
    }

    struct Context: Decodable {
        let incarnation: UInt64
        let ownerGeneration: UInt64
        let metadataOp: UInt64
    }

    struct Message: Decodable {
        let offset: UInt64
        let id: String
        let timestamp: UInt64
        let originTimestamp: UInt64
        let payload: String
    }

    struct Section: Decodable {
        let partitionId: UInt32
        let status: UInt32
        let currentOffset: UInt64
        let messagesCount: UInt32
        let context: Context
        let nextOffset: UInt64
        let recordsLen: Int
        let messages: [Message]
    }

    struct Reply: Decodable {
        let `case`: String
        let sections: [Section]
        let bodyHex: String
    }

    struct Refused: Decodable {
        let `case`: String
        let bodyHex: String
    }

    struct RefusedSet: Decodable {
        let fetches: [Refused]
        let fetchReplies: [Refused]
    }

    struct Constants: Decodable {
        let codes: [String: UInt32]
        let statusOk: UInt32
        let errors: [String: UInt32]
        let minDeferredPollMaxBytes: UInt32
        let maxDeferredPollWaitUs: UInt64
        let maxDeferredPollTimeoutUs: UInt64
        let minDeferredPollReplyMarginUs: UInt64
        let maxPartitionsPerRequest: Int
        let maxRecordReplySize: Int
        let requestHeaderSize: Int
        let fetchSectionHeaderSize: Int
    }

    let schemaVersion: Int
    let constants: Constants
    let deferredPolls: [Case<DeferredPoll>]
    let fetches: [Case<Fetch>]
    let cancellations: [Cancellation]
    let fetchReplies: [Reply]
    let refused: RefusedSet

    static func load() throws -> DeferredPollingFixture {
        let url = try #require(Bundle.module.url(forResource: "deferred_polling", withExtension: "json", subdirectory: "Fixtures"))
        let decoder = JSONDecoder()
        decoder.keyDecodingStrategy = .convertFromSnakeCase
        return try decoder.decode(DeferredPollingFixture.self, from: try Data(contentsOf: url))
    }
}

extension DeferredPollingFixture.WireIdentifier {
    var identifier: Identifier {
        get throws {
            switch value {
            case .number(let number): Identifier(numeric: number)
            case .string(let name): try Identifier(named: name)
            }
        }
    }
}

extension DeferredPollingFixture.WireConsumer {
    var consumer: Consumer {
        get throws {
            Consumer(kind: try #require(Consumer.Kind(rawValue: kind)), id: try id.identifier)
        }
    }
}

extension DeferredPollingFixture.Strategy {
    var strategy: PollingStrategy {
        get throws {
            PollingStrategy(kind: try #require(PollingStrategy.Kind(rawValue: kind)), value: value)
        }
    }
}

extension DeferredPollingFixture.Context {
    var context: PartitionContext {
        PartitionContext(incarnation: incarnation, ownerGeneration: ownerGeneration, metadataOp: metadataOp)
    }
}

/// A decimal message id of up to 128 bits.
private func messageID(_ decimal: String) throws -> MessageID {
    var high: UInt64 = 0
    var low: UInt64 = 0
    for character in decimal {
        let digit = UInt64(try #require(character.wholeNumberValue))
        let lowProduct = low.multipliedFullWidth(by: 10)
        let (sum, carry) = lowProduct.low.addingReportingOverflow(digit)
        low = sum
        high = high &* 10 &+ lowProduct.high &+ (carry ? 1 : 0)
    }
    return MessageID(low: low, high: high)
}

@Suite("Deferred polling wire vectors")
struct DeferredPollingVectorTests {
    private let fixture: DeferredPollingFixture

    init() throws {
        fixture = try DeferredPollingFixture.load()
    }

    @Test func theConstantsMatchTheClient() throws {
        let constants = fixture.constants
        #expect(fixture.schemaVersion == 1)
        // Foundation converts the keys of these tables to camelCase on some
        // platforms only, so both spellings are looked up.
        #expect(Self.entry(constants.codes, "poll_messages") == CommandCode.pollMessages.rawValue)
        #expect(Self.entry(constants.codes, "poll_messages_deferred") == CommandCode.pollMessagesDeferred.rawValue)
        #expect(Self.entry(constants.codes, "cancel_deferred_request") == CommandCode.cancelDeferredRequest.rawValue)
        #expect(Self.entry(constants.codes, "fetch_messages") == CommandCode.fetchMessages.rawValue)
        #expect(constants.errors.count == 9)
        for (_, code) in constants.errors {
            let name = try #require(IggyErrorCode(rawValue: code)?.name)
            #expect(Self.entry(constants.errors, name) == code, "\(name)")
        }
        #expect(constants.statusOk == 0)
        #expect(constants.minDeferredPollMaxBytes == DeferredPollOptions.minMaxBytes)
        #expect(constants.maxDeferredPollWaitUs == DeferredPollOptions.maxWaitMicroseconds)
        #expect(constants.maxDeferredPollTimeoutUs == DeferredPollOptions.maxRequestTimeoutMicroseconds)
        #expect(constants.minDeferredPollReplyMarginUs == DeferredPollOptions.replyMarginMicroseconds)
        #expect(constants.maxPartitionsPerRequest == Requests.maxPartitionsPerRequest)
        #expect(constants.requestHeaderSize == VSRFrame.headerSize)
        #expect(constants.fetchSectionHeaderSize == Responses.fetchSectionHeaderSize)
        // A reply that holds the largest record fits the frames the client reads.
        #expect(constants.maxRecordReplySize <= VSRFrame.maxFrameSize)
    }

    private static func entry(_ table: [String: UInt32], _ snakeCase: String) -> UInt32? {
        let words = snakeCase.split(separator: "_")
        let camelCase = words.prefix(1).joined() + words.dropFirst().map { $0.prefix(1).uppercased() + $0.dropFirst() }.joined()
        return table[snakeCase] ?? table[camelCase]
    }

    @Test func deferredPollsEncodeAsTheVectors() throws {
        for vector in fixture.deferredPolls {
            let request = vector.request
            let options = DeferredPollOptions(
                maxWait: .microseconds(request.waitUs), minCount: request.minCount, maxBytes: request.maxBytes,
                requestTimeout: .microseconds(request.requestTimeoutUs))
            try options.validate(count: request.count)
            let body = try Requests.pollMessages(
                consumer: try request.consumer.consumer, streamID: try request.streamId.identifier, topicID: try request.topicId.identifier,
                partitionID: request.partitionId, strategy: try request.strategy.strategy, count: request.count, autoCommit: request.autoCommit,
                options: options)
            #expect(body == [UInt8](hex: vector.bodyHex), "\(vector.case)")
        }
    }

    @Test func fetchesEncodeAsTheVectors() throws {
        for vector in fixture.fetches {
            let request = vector.request
            let options = DeferredPollOptions(
                maxWait: .microseconds(request.waitUs), minCount: request.minCount, maxBytes: request.maxBytes,
                requestTimeout: .microseconds(request.requestTimeoutUs))
            let targets = try request.targets.map { target in
                Requests.FetchTarget(
                    partitionID: target.partitionId, strategy: try target.strategy.strategy, maxBytes: target.maxBytes,
                    fence: PartitionContext(incarnation: target.incarnation, ownerGeneration: target.ownerGeneration, metadataOp: 0))
            }
            let body = try Requests.fetchMessages(
                consumer: try request.consumer.consumer, streamID: try request.streamId.identifier, topicID: try request.topicId.identifier,
                targets: targets, count: request.count, autoCommit: request.autoCommit, options: options)
            #expect(body == [UInt8](hex: vector.bodyHex), "\(vector.case)")
            // The client reads each vector back as a fetch it accepts.
            let decoded = try RawRequest.fetch(body)
            #expect(decoded.targets == targets, "\(vector.case)")
        }
    }

    /// A cancellation repeats the header of the request it cancels with its
    /// own code, no body and no partition context. The vectors are taken
    /// before the transport stamps the checksums.
    @Test func cancellationsRepeatTheHeaderOfTheirRequest() throws {
        for vector in fixture.cancellations {
            var session = ConsensusSession(clientID: UInt128Value(low: vector.client, high: 0))
            try session.bind(vector.session)
            for _ in 1..<vector.request {
                _ = try session.nextRequestID()
            }
            let request = try VSRFrame.encodeRequest(
                session: &session, code: vector.cancelsCode, payload: [1, 2, 3],
                partitionContext: PartitionContext(incarnation: 5, ownerGeneration: 6, metadataOp: 7))
            #expect(request.requestID == vector.request, "\(vector.case)")
            var cancellation = try #require(request.deferredCancellation, "\(vector.case)")
            cancellation.replaceSubrange(0..<32, with: repeatElement(0, count: 32))
            #expect(cancellation == [UInt8](hex: vector.headerHex), "\(vector.case)")
        }
    }

    @Test func fetchRepliesDecodeAsTheVectors() throws {
        for vector in fixture.fetchReplies {
            let sections = try Responses.fetchSections([UInt8](hex: vector.bodyHex)[...])
            #expect(sections.map(\.partitionID) == vector.sections.map(\.partitionId), "\(vector.case)")
            for (section, expected) in zip(sections, vector.sections) {
                let label = "\(vector.case), partition \(expected.partitionId)"
                #expect(section.status == expected.status, "\(label)")
                #expect(section.currentOffset == expected.currentOffset, "\(label)")
                #expect(section.messagesCount == expected.messagesCount, "\(label)")
                #expect(section.context == expected.context.context, "\(label)")
                #expect(section.nextOffset == expected.nextOffset, "\(label)")
                #expect(section.records.count == expected.recordsLen, "\(label)")
                guard expected.status == 0 else {
                    #expect(section.error?.rawCode == expected.status, "\(label)")
                    continue
                }
                let messages = try section.decode().messages
                #expect(messages.map(\.offset) == expected.messages.map(\.offset), "\(label)")
                #expect(messages.map(\.payloadString) == expected.messages.map(\.payload), "\(label)")
                #expect(messages.map(\.timestamp.microseconds) == expected.messages.map(\.timestamp), "\(label)")
                #expect(messages.map(\.originTimestamp.microseconds) == expected.messages.map(\.originTimestamp), "\(label)")
                #expect(messages.map(\.id) == (try expected.messages.map { try messageID($0.id) }), "\(label)")
            }
        }
    }

    @Test func refusedFetchesAndRepliesFail() {
        for vector in fixture.refused.fetches {
            #expect(throws: IggyError.self, "\(vector.case)") { try RawRequest.fetch([UInt8](hex: vector.bodyHex)) }
        }
        for vector in fixture.refused.fetchReplies {
            #expect(throws: (any Error).self, "\(vector.case)") { try Responses.fetchSections([UInt8](hex: vector.bodyHex)[...]) }
        }
    }
}
